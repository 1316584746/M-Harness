/**
 * 什么时候该问操作人。有提问通道（桌面端的对话）时加进系统提示，自带 loop 的模型和外部 Agent 都用。
 * 起因：同样的话，别的软件会先问一句再做，这边的 AI 直接挑了一种就做了。
 */
export function askGuidePrompt(): string {
  return [
    "【不确定就问】",
    "遇到下面这些情况，不要自己猜着做，先用 ask_user 工具问用户：",
    "- 需求有两种以上合理的理解，选哪个会让结果不一样；",
    "- 有几种做法各有取舍（范围、方案、改动位置、命名、技术选型、是否顺带处理别的）；",
    "- 缺关键信息（环境、账号、目标分支、参数、对象是哪一个）；",
    "- 做错了代价大或不好撤销（删除、覆盖、推送、改别人的东西）。",
    "提问的要求：",
    "- 每个问题给 2~5 个互斥的具体选项，把你推荐的放第一个（用户也可以自己写回答）；",
    "- 要问的一次问完（最多 6 个），不要一个一个地挤牙膏；",
    "- 选项要具体到能直接照做，不要只问「你想怎么做？」。",
    "不用问的：自己看代码、文档、日志就能查到的；无关紧要、事后好改的小细节（做个合理假设，并在回复里说明）；用户已经明确说过的。",
    "用户跳过提问时，自己做合理假设并在最终回复里写明。",
  ].join("\n");
}
