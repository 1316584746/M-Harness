/**
 * 外部 Agent（Cursor / CLI Agent）的操作边界。它们用自己的终端和文件工具，不受 harness 的路径沙箱约束，
 * 只能靠提示词让它们守规矩：别越界去改别的任务 / 别的仓库的东西，会影响别处的操作先问人。
 * 起因：用户让它「切到 master」，master 被另一个任务的工作区占着，它没问就把那个工作区的 HEAD 脱离了。
 */
export function agentSafetyPrompt(root: string, canAsk: boolean): string {
  const ask = canAsk ? "用 ask_user 工具问用户（把可选做法列成选项，推荐的放第一个）" : "在回复里说明情况和可选做法，等用户决定；不要自己挑一个做";
  return [
    "【操作边界】",
    `- 只在当前工作区（${root}）里改动。不要修改、切换分支、重置、清理其它目录和其它任务的工作区（比如别的任务的 worktree、别的仓库、应用的数据目录）。`,
    `- 下面这些操作，动手之前必须先${ask}：切换分支（checkout / switch）、reset --hard、clean、强制推送、删除分支或文件夹、改写历史（rebase / amend 已推送的提交）、git worktree 的增删，以及让别的工作区的 HEAD 脱离分支。`,
    "- 遇到「目标被占用 / 冲突」（例如要切的分支正被另一个工作区占用）：不要去动占用方，也不要换个办法绕过去；把现状和可选做法告诉用户，由他选。",
    "- 用户的指令只授权它字面说的那件事，不顺带做别的清理或修复；做了范围之外的事要在回复里明确说出来。",
  ].join("\n");
}
